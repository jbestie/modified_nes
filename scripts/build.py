#!/usr/bin/env python3
"""Deterministic build of one game: original ROM + src/*.asm -> build/*.nes + dist/*.bps

Usage: build.py <game> [--rom PATH]

<game> is a name under games/ (or a path to a game directory) whose game.py
defines the expected input, the targets and the patches.  Input defaults to
<game>/rom/original.nes; outputs go to <game>/build, <game>/dist and
<game>/notes/patch_ranges.md.

Steps (fails loudly on any mismatch):
  1. Validate the input image (iNES magic, mapper, PRG/CHR size, no trainer,
     PRG CRC32 from game.py).  Any header variant works if the PRG matches.
  2. Assemble each target; every patched byte must have a matching preimage.
  3. Write build/<target>.nes, a listing, a byte-level patch map and symbols.
  4. Diff the output against the input: the changed bytes must be exactly the
     assembled ones and the 16-byte header must be untouched.
  5. Create dist/*.bps (plus one per other known header variant) and verify
     that applying each patch to its input reproduces the output bit-for-bit.

A target with an expansion (UxROM, e.g. 8 -> 16 x 16K) is built on: the
original banks unchanged, the new banks $FF, the last bank a copy of the
original fixed bank.  Only the header's PRG size byte changes besides the
assembled bytes.
"""
import argparse
import hashlib
import pathlib
import sys
import zlib

sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
import asm6502  # noqa: E402
import bps  # noqa: E402
import gamedef  # noqa: E402
from gamedef import rel  # noqa: E402
from rom_info import parse  # noqa: E402


def expand_uxrom(prg, banks):
    """n x 16K -> banks x 16K: original banks as is, new ones empty, last = fixed bank copy."""
    n = len(prg) // 0x4000
    assert n < banks < 256
    return prg + b"\xFF" * ((banks - n - 1) * 0x4000) + prg[-0x4000:]


def expanded_header(header, banks):
    h = bytearray(header)
    h[4] = banks                # PRG size in 16K units (NES 2.0: MSB nibble stays 0)
    return bytes(h)


def die(msg):
    print(f"BUILD FAILED: {msg}", file=sys.stderr)
    sys.exit(1)


def write_ranges(path, name, records, first, base_banks, banks):
    """notes/patch_ranges.md: contiguous patched ranges (generated)."""
    ranges = []
    for bank, addr, off, old, new, src in records:
        if ranges and ranges[-1]["bank"] == bank and ranges[-1]["end"] == addr \
                and ranges[-1]["src"] == src:
            r = ranges[-1]
            r["end"] += 1
            r["old"].append(old)
            r["new"].append(new)
        else:
            ranges.append(dict(bank=bank, start=addr, end=addr + 1, off=off, old=[old], new=[new],
                               src=src))
    with open(path, "w" if first else "a") as f:
        if first:
            f.write("# Patched byte ranges (generated by scripts/build.py)\n\n"
                    "PRG offset excludes the 16-byte iNES header; file offset includes it.\n")
        f.write(f"\n## build/{name}.nes\n\n")
        if banks:
            n = base_banks
            f.write(f"{banks * 16} KiB image: banks 0-{n - 1} = the original, {n}-{banks - 2} = new "
                    f"(`$FF` where nothing is listed below), {banks - 1} = copy of the fixed bank {n - 1} "
                    f"(patched below).  Header byte 4 (PRG size) `${n:02X}` -> `${banks:02X}`.\n\n")
        f.write("| Bank | CPU | PRG off | File off | Len | Original bytes | New bytes | Source |\n")
        f.write("|---|---|---|---|---|---|---|---|\n")
        for r in ranges:
            n = r['end'] - r['start']
            if n > 48:
                old = f"{n} bytes" + (" of $FF (new bank)" if set(r['old']) == {0xFF} else "")
                new = f"new code, see build/{name}.lst"
            else:
                old, new = f"`{bytes(r['old']).hex(' ')}`", f"`{bytes(r['new']).hex(' ')}`"
            f.write(f"| {r['bank']} | ${r['start']:04X} | ${r['off']:05X} | ${r['off'] + 16:05X} | "
                    f"{n} | {old} | {new} | {pathlib.Path(r['src']).name} |\n")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("game", help=f"game name under games/ ({', '.join(gamedef.names())}) or its directory")
    ap.add_argument("--rom", help="input ROM (default: <game>/rom/original.nes)")
    a = ap.parse_args()
    game = gamedef.load(a.game)
    rom_path = pathlib.Path(a.rom) if a.rom else game.DIR / "rom" / "original.nes"
    if not rom_path.exists():
        die(f"{rel(rom_path)} not found. Copy your own {game.TITLE} dump there.")
    data = rom_path.read_bytes()
    try:
        r = parse(data)
    except ValueError as e:
        die(str(e))
    prg = r["prg"]
    checks = [
        (r["mapper"] == game.MAPPER, f"mapper {r['mapper']} (expected {game.MAPPER})"),
        (r["prg_banks"] == game.PRG_BANKS, f"{r['prg_banks']} PRG banks (expected {game.PRG_BANKS})"),
        (r["chr_banks"] == game.CHR_BANKS, f"{r['chr_banks']} CHR banks (expected {game.CHR_BANKS})"),
        (not r["trainer"], "trainer present"),
        (r["trailing"] == 0, f"{r['trailing']} trailing bytes"),
        (zlib.crc32(prg) == game.PRG_CRC,
         f"PRG CRC32 {zlib.crc32(prg):08X} (expected {game.PRG_CRC:08X})"),
    ]
    for ok, msg in checks:
        if not ok:
            die(f"unsupported input ROM: {msg}")
    file_crc = zlib.crc32(data)
    known = {crc: v[0] for crc, v in game.HEADERS.items()}
    print(f"input  {rel(rom_path)}  CRC32 {file_crc:08X} "
          f"({known.get(file_crc, 'unknown header variant, PRG OK')})")

    build, dist = game.DIR / "build", game.DIR / "dist"
    build.mkdir(exist_ok=True)
    dist.mkdir(exist_ok=True)
    header = data[:16]
    outputs = {}
    for i, (name, sources, banks) in enumerate(game.TARGETS):
        base_prg = expand_uxrom(prg, banks) if banks else prg
        out_header = expanded_header(header, banks) if banks else header
        base = out_header + base_prg
        try:
            new_prg, records, listing, symbols = asm6502.assemble(
                base_prg, [str(game.DIR / s) for s in sources])
        except asm6502.AsmError as e:
            die(str(e))
        out = out_header + new_prg
        # Independent diff check against the (expanded) input image
        changed = {i for i in range(len(base)) if base[i] != out[i]}
        expected = {16 + off for (_, _, off, old, new, _) in records if old != new}
        if changed != expected:
            die(f"{name}: diff does not match assembled records")
        hdr_diff = [i for i in range(16) if out[i] != header[i]]
        if hdr_diff != ([4] if banks else []):
            die(f"{name}: unexpected header change at bytes {hdr_diff}")
        if banks and base_prg[:len(prg)] != prg:
            die(f"{name}: expansion altered the original banks")
        path = build / f"{name}.nes"
        path.write_bytes(out)
        outputs[name] = (out, banks)
        with open(build / f"{name}.lst", "w") as f:
            for src, bank, addr, bs, text in listing:
                f.write(f"{bank:2}:{addr:04X}  {bs.hex(' '):<12} {text}    ; {pathlib.Path(src).name}\n")
        with open(build / f"{name}.patchmap.txt", "w") as f:
            f.write("bank cpu   prg_off file_off old new  source\n")
            for bank, addr, off, old, new, src in records:
                f.write(f"{bank:<4} {addr:04X} {off:05X}   {off + 16:05X}    {old:02X}  {new:02X}   "
                        f"{pathlib.Path(src).name}\n")
        with open(build / f"{name}.sym", "w") as f:   # for the Lua tests
            for sym, val in sorted(symbols.items()):
                f.write(f"{sym} = ${val:04X}\n")
        write_ranges(game.DIR / "notes" / "patch_ranges.md", name, records, i == 0, r["prg_banks"], banks)
        size = f", {len(new_prg) // 1024} KiB PRG" if banks else ""
        print(f"output {rel(path)}  CRC32 {zlib.crc32(out):08X}  "
              f"SHA1 {hashlib.sha1(out).hexdigest()}  ({len(changed)} bytes changed{size})")

    for target, stem, meta in game.PATCHES:
        final, banks = outputs[target]
        patch = bps.create(data, final, meta)
        ppath = dist / f"{stem}.bps"
        ppath.write_bytes(patch)
        if bps.apply(patch, data) != final:
            die(f"{stem}: BPS round-trip mismatch")
        print(f"patch  {rel(ppath)}  ({len(patch)} bytes) round-trip OK "
              f"(source CRC32 {file_crc:08X})")

        # The same patch for the other known header variants (PRG identical).
        for alt_crc, (label, tag, alt_header) in game.HEADERS.items():
            if alt_crc == file_crc:
                continue
            alt_src = alt_header + data[16:]
            if zlib.crc32(alt_src) != alt_crc:
                die(f"game.py HEADERS: {tag} header gives CRC32 {zlib.crc32(alt_src):08X}, not {alt_crc:08X}")
            alt_dst = (expanded_header(alt_header, banks) if banks else alt_header) + final[16:]
            alt_patch = bps.create(alt_src, alt_dst, meta)
            if bps.apply(alt_patch, alt_src) != alt_dst:
                die(f"{stem}: alternate BPS round-trip mismatch")
            apath = dist / f"{stem}.{tag}.bps"
            apath.write_bytes(alt_patch)
            print(f"patch  {rel(apath)}  ({len(alt_patch)} bytes) for source CRC32 {alt_crc:08X} "
                  f"({label}) -> CRC32 {zlib.crc32(alt_dst):08X}")


if __name__ == "__main__":
    main()
