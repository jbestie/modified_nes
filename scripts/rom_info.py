#!/usr/bin/env python3
"""Inspect an iNES image and emit a Markdown layout report.

Usage: rom_info.py <rom.nes> [--game NAME] [--md out.md]

Without --game: a plain report of any iNES image (a first look at a new game).
With --game (a name under games/ or a game directory): the report names the
game and its known header variants, and the exit status is non-zero unless
the image is the PRG, mapper and size that games/<name>/game.py expects.
"""
import argparse
import hashlib
import pathlib
import sys
import zlib

MAPPER_NAMES = {0: "NROM", 1: "MMC1", 2: "UNROM/UxROM", 3: "CNROM", 4: "MMC3", 7: "AxROM"}


def parse(data):
    if data[:4] != b"NES\x1a":
        raise ValueError("missing iNES magic")
    h = data[:16]
    f6, f7 = h[6], h[7]
    nes2 = (f7 & 0x0C) == 0x08
    trainer = bool(f6 & 0x04)
    prg_banks = h[4] | (((h[9] & 0x0F) << 8) if nes2 else 0)
    chr_banks = h[5] | (((h[9] & 0xF0) << 4) if nes2 else 0)
    mapper = (f6 >> 4) | (f7 & 0xF0) | (((h[8] & 0x0F) << 8) if nes2 else 0)
    prg_off = 16 + (512 if trainer else 0)
    prg = data[prg_off:prg_off + prg_banks * 0x4000]
    chr_ = data[prg_off + len(prg):prg_off + len(prg) + chr_banks * 0x2000]
    trailing = len(data) - (prg_off + len(prg) + len(chr_))
    return dict(header=h, nes2=nes2, trainer=trainer, prg_banks=prg_banks,
                chr_banks=chr_banks, mapper=mapper, prg_off=prg_off, prg=prg,
                chr=chr_, trailing=trailing,
                mirroring="vertical" if f6 & 1 else "horizontal",
                battery=bool(f6 & 2), four_screen=bool(f6 & 8))


def free_runs(prg, min_len=16):
    """Runs of $FF or $00 of at least min_len bytes, per 16K bank."""
    runs = []
    for bank in range(len(prg) // 0x4000):
        b = prg[bank * 0x4000:(bank + 1) * 0x4000]
        i = 0
        while i < len(b):
            v = b[i]
            if v in (0x00, 0xFF):
                j = i
                while j < len(b) and b[j] == v:
                    j += 1
                if j - i >= min_len:
                    runs.append((bank, i, j - i, v))
                i = j
            else:
                i += 1
    return runs


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("rom")
    ap.add_argument("--game", help="check against games/<name>/game.py")
    ap.add_argument("--md")
    a = ap.parse_args()
    game = None
    if a.game:
        sys.path.insert(0, str(pathlib.Path(__file__).resolve().parent))
        import gamedef
        game = gamedef.load(a.game)
    known = {crc: v[0] for crc, v in game.HEADERS.items()} if game else {}
    data = open(a.rom, "rb").read()
    r = parse(data)
    prg = r["prg"]
    prg_crc = zlib.crc32(prg)
    file_crc = zlib.crc32(data)
    vec = prg[-6:]
    nmi, reset, irq = (vec[0] | vec[1] << 8, vec[2] | vec[3] << 8, vec[4] | vec[5] << 8)

    lines = []
    w = lines.append
    w(f"# ROM layout — {game.TITLE if game else pathlib.Path(a.rom).name}\n")
    w(f"Generated by `scripts/rom_info.py` from the actual bytes of `{a.rom}`.\n")
    w("## File and checksums\n")
    w("| Item | Value |\n|---|---|")
    w(f"| File size | {len(data)} bytes |")
    w(f"| File CRC32 | `{file_crc:08X}` ({known.get(file_crc, 'unrecognised header variant')}) |")
    w(f"| File SHA-1 | `{hashlib.sha1(data).hexdigest()}` |")
    w(f"| File MD5 | `{hashlib.md5(data).hexdigest()}` |")
    expect = f" (expected `{game.PRG_CRC:08X}`: {'MATCH' if prg_crc == game.PRG_CRC else 'MISMATCH'})" if game else ""
    w(f"| PRG CRC32 | `{prg_crc:08X}`{expect} |")
    w(f"| PRG SHA-1 | `{hashlib.sha1(prg).hexdigest()}` |")
    w("")
    w("## iNES header\n")
    w(f"Raw: `{r['header'].hex(' ')}`\n")
    w("| Field | Value |\n|---|---|")
    w(f"| Format | {'NES 2.0' if r['nes2'] else 'iNES 1.0'} |")
    w(f"| Mapper | {r['mapper']} ({MAPPER_NAMES.get(r['mapper'], '?')}) |")
    w(f"| PRG-ROM | {r['prg_banks']} × 16 KiB = {len(prg)} bytes |")
    w(f"| CHR-ROM | {r['chr_banks']} × 8 KiB ({'none → CHR-RAM' if r['chr_banks'] == 0 else 'present'}) |")
    w(f"| Mirroring | {r['mirroring']} |")
    w(f"| Battery | {r['battery']} |")
    w(f"| Trainer | {r['trainer']} |")
    w(f"| Four-screen | {r['four_screen']} |")
    w(f"| Bytes after PRG/CHR | {r['trailing']} |")
    w("")
    # UxROM: last 16K bank fixed at $C000, the others switch in at $8000.
    # Other mappers: the CPU window column is left out (and the CPU addresses
    # in the free-space table assume the UxROM layout).
    uxrom = r["mapper"] == 2
    w(f"## Bank map{' (UNROM)' if uxrom else ''}\n")
    if uxrom:
        w("PRG file offset = 16 (header) + bank × $4000 + (CPU address − bank base).\n")
        w("| Bank | CPU window | PRG offset | File offset |\n|---|---|---|---|")
    else:
        w("16 KiB units; CPU windows depend on the mapper.\n")
        w("| Bank | PRG offset | File offset |\n|---|---|---|")
    for b in range(r["prg_banks"]):
        base = 0xC000 if b == r["prg_banks"] - 1 else 0x8000
        kind = "fixed" if base == 0xC000 else "switchable"
        window = f" ${base:04X}–${base + 0x3FFF:04X} ({kind}) |" if uxrom else ""
        w(f"| {b} |{window} ${b * 0x4000:05X} | ${b * 0x4000 + r['prg_off']:05X} |")
    w("")
    w(f"## Vectors ({'fixed' if uxrom else 'last'} bank)\n")
    w(f"NMI = `${nmi:04X}`, RESET = `${reset:04X}`, IRQ/BRK = `${irq:04X}`\n")
    w("## Candidate free space (runs of $00/$FF ≥ 16 bytes)\n")
    w("Raw scan only." + (" " + game.LAYOUT_NOTE if game and getattr(game, "LAYOUT_NOTE", "") else "") + "\n")
    w("| Bank | CPU start | Length | Fill | PRG offset |\n|---|---|---|---|---|")
    for bank, off, ln, v in free_runs(prg):
        base = 0xC000 if bank == r["prg_banks"] - 1 else 0x8000
        w(f"| {bank} | ${base + off:04X} | {ln} | ${v:02X} | ${bank * 0x4000 + off:05X} |")
    w("")
    md = "\n".join(lines)
    if a.md:
        open(a.md, "w").write(md)
    else:
        print(md)

    ok = not game or (prg_crc == game.PRG_CRC and r["mapper"] == game.MAPPER
                      and r["prg_banks"] == game.PRG_BANKS and r["chr_banks"] == game.CHR_BANKS
                      and not r["trainer"])
    if not ok:
        print("ERROR: unsupported ROM variant (see report)", file=sys.stderr)
        sys.exit(1)


if __name__ == "__main__":
    main()
